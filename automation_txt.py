    "    # =======================================================\n",
    "    # Extract quoted text\n",
    "    # =======================================================\n",
    "\n",
    "    def get_text(self, line):\n",
    "\n",
    "        first = line.find('\"')\n",
    "        last = line.rfind('\"')\n",
    "\n",
    "        if first == -1 or last == -1 or first == last:\n",
    "            return \"\"\n",
    "\n",
    "        return line[first + 1:last]\n",
    "\n",
    "    # =======================================================\n",
    "    # Replace quoted text\n",
    "    # =======================================================\n",
    "\n",
    "    def replace_text(self, line, new_text):\n",
    "\n",
    "        first = line.find('\"')\n",
    "        last = line.rfind('\"')\n",
    "\n",
    "        if first == -1 or last == -1 or first == last:\n",
    "            return line\n",
    "\n",
    "        return line[:first + 1] + new_text + line[last:]\n",
    "\n",
    "    # =======================================================\n",
    "    # Detect numbers\n",
    "    # =======================================================\n",
    "\n",
    "    def extract_numbers(self, text):\n",
    "\n",
    "        return re.findall(r'\\b\\d+\\b', text)\n",
    "\n",
    "    # =======================================================\n",
    "    # Remove numbers\n",
    "    # =======================================================\n",
    "\n",
    "    def remove_numbers(self, text):\n",
    "\n",
    "        text = re.sub(r'\\b\\d+\\b', '', text)\n",
    "\n",
    "        # remove duplicate spaces\n",
    "        text = re.sub(r'\\s+', ' ', text)\n",
    "\n",
    "        return text.strip()\n",
    "\n",
    "    # =======================================================\n",
    "    # Rule Engine (Version 0.1)\n",
    "    # =======================================================\n",
    "\n",
    "    def classify(self, text):\n",
    "\n",
    "        # Empty text\n",
    "        if text == \"\":\n",
    "\n",
    "            return {\n",
    "                \"decision\": \"LNA_ONLY\",\n",
