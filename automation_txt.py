    "                \"sach\": None\n",
    "            }\n",
    "\n",
    "        numbers = self.extract_numbers(text)\n",
    "\n",
    "        # Text only\n",
    "        if len(numbers) == 0:\n",
    "\n",
    "            return {\n",
    "                \"decision\": \"SACH_ONLY\",\n",
    "                \"lna\": None,\n",
